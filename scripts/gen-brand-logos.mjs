// Build-time generator: extracts Simple Icons SVG paths into a typed module.
// Keeps the brand wall self-hosted (no CDN) and tree-shakeable.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ICONS_DIR = join(process.cwd(), "node_modules", "simple-icons", "icons");
const WANTED = [
  "react",
  "nextdotjs",
  "vuedotjs",
  "angular",
  "nodedotjs",
  "langchain",
  "langgraph",
  "pydantic",
  "crewai",
  "anthropic",
  "temporal",
  "docker",
  "kubernetes",
  "github",
  "discord",
  "whatsapp",
  "telegram",
];

const out = {};
for (const slug of WANTED) {
  const file = join(ICONS_DIR, `${slug}.svg`);
  let svg;
  try {
    svg = readFileSync(file, "utf8");
  } catch {
    console.warn(`skip (missing): ${slug}`);
    continue;
  }
  const title = /<title>([^<]+)<\/title>/.exec(svg)?.[1] ?? slug;
  const path = /<path[^>]*\sd="([^"]+)"/.exec(svg)?.[1];
  if (!path) {
    console.warn(`skip (no path): ${slug}`);
    continue;
  }
  out[slug] = { title, path };
}

const all = readdirSync(ICONS_DIR).filter((f) => f.endsWith(".svg")).length;

const body = `// AUTO-GENERATED by scripts/gen-brand-logos.mjs. Do not edit by hand.
// Source: simple-icons@${JSON.parse(readFileSync(join(process.cwd(), "node_modules", "simple-icons", "package.json"), "utf8")).version} (${all} icons available, ${Object.keys(out).length} inlined)

export interface BrandLogo {
  /** Display name, also used as the accessible label. */
  readonly title: string;
  /** Single-path SVG geometry, viewBox is always 0 0 24 24. */
  readonly path: string;
}

export const brandLogos = {
${Object.entries(out)
  .map(([slug, v]) => `  ${slug}: { title: ${JSON.stringify(v.title)}, path: ${JSON.stringify(v.path)} },`)
  .join("\n")}
} as const satisfies Record<string, BrandLogo>;

export type BrandSlug = keyof typeof brandLogos;

export function getBrandLogo(slug: string): BrandLogo | undefined {
  return (brandLogos as Record<string, BrandLogo>)[slug];
}
`;

writeFileSync(join(process.cwd(), "src", "data", "brand-logos.ts"), body, "utf8");
console.log(`wrote ${Object.keys(out).length} logos`);